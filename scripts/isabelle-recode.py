def recode(text):
    return "".join(MAP.get(c, c) for c in text)

if __name__ == "__main__":
    for name in sys.argv[1:]:
        p = pathlib.Path(name)
        t = p.read_text(encoding="utf-8")
        r = recode(t)
        if r != t:
            p.write_text(r, encoding="utf-8")
